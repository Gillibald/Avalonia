namespace Avalonia.Media.Imaging
{
    /// <summary>
    /// The well-known encode target formats with a built-in encoder class.
    /// </summary>
    public enum BitmapFileFormat
    {
        /// <summary>Portable Network Graphics.</summary>
        Png,

        /// <summary>JPEG.</summary>
        Jpeg,

        /// <summary>Tagged Image File Format.</summary>
        Tiff,

        /// <summary>Graphics Interchange Format.</summary>
        Gif,

        /// <summary>WebP.</summary>
        Webp,

        /// <summary>Windows Bitmap.</summary>
        Bmp,
    }
}
